import numpy as np
import plotly.express as px
import streamlit as st

from core import analytics as A
from core.agent import llm_narrative
from core.ui import get_df, insight, page_header, style

df = get_df()
page_header("AI Layer", "AI Insights, Anomaly Detection & District Typologies",
            "Unsupervised machine learning finds unusual districts and natural groupings; generative AI writes the briefing.")

tab1, tab2, tab3 = st.tabs(["📝 AI executive briefing", "🚨 Anomaly detection", "🧩 District typologies"])

with tab1:
    facts = A.auto_insights(df)
    if st.button("✨ Generate executive briefing", type="primary"):
        with st.spinner("Writing briefing from verified facts…"):
            text, mode = llm_narrative(facts, "Write a 150-word executive briefing for a provincial planning "
                                              "secretary, then 3 recommended priorities.")
        st.session_state["exec_summary"] = text
        st.session_state["exec_mode"] = mode
    if "exec_summary" in st.session_state:
        st.caption(f"Generated by: {st.session_state['exec_mode']} · grounded only in the facts below · "
                   "used as the executive summary of the PDF report")
        insight(st.session_state["exec_summary"], ai=True)
    st.markdown("##### Verified facts (computed from the data)")
    for f in facts:
        insight(f)

with tab2:
    st.markdown("An **Isolation Forest** looks at each district's combination of growth, sex ratio, household size, "
                "urbanisation change, age structure and literacy, and isolates the ones that don't fit the pattern. "
                "These are candidates for **data-quality checks** (possible over/under-count, boundary changes) "
                "or for **policy attention**.")
    cont = st.slider("Expected share of anomalies", 0.03, 0.15, 0.08, 0.01)
    an = A.detect_anomalies(df, contamination=cont)
    flagged = an[an["is_anomaly"]]
    c1, c2 = st.columns([3, 2])
    with c1:
        an["status"] = np.where(an["is_anomaly"], "Anomaly", "Normal")
        fig = px.scatter(an, x="growth_rate", y="females_per_100_males", color="status", size="pop_2023",
                         hover_name="district", size_max=34,
                         color_discrete_map={"Anomaly": "#f43f5e", "Normal": "#c4b5fd"},
                         hover_data={"why": True, "pop_2023": ":,", "status": False})
        fig.update_traces(marker=dict(line=dict(color="#fff", width=1)))
        fig.update_layout(xaxis_title="Growth %/yr", yaxis_title="Females per 100 males")
        st.plotly_chart(style(fig, 460, "Districts in indicator space - red = flagged"), width="stretch")
    with c2:
        st.markdown(f"##### {len(flagged)} flagged districts")
        st.dataframe(flagged[["district", "province", "anomaly_score", "why"]]
                     .style.format({"anomaly_score": "{:.3f}"}), hide_index=True, width="stretch", height=430)

with tab3:
    k = st.slider("Number of typologies (K-Means clusters)", 3, 6, 4)
    lab, prof = A.cluster_districts(df, k)
    c1, c2 = st.columns([3, 2])
    with c1:
        fig = px.scatter(lab, x="urban_pct", y="literacy_rate", color="typology", size="pop_2023", size_max=36,
                         hover_name="district", color_discrete_sequence=["#7c3aed", "#f97316", "#14b8a6", "#eda100",
                                                                         "#ec4899", "#e87ba4"],
                         hover_data={"province": True, "growth_rate": ":.2f", "pop_2023": ":,"})
        fig.update_traces(marker=dict(line=dict(color="#fff", width=1)))
        fig.update_layout(xaxis_title="Urban %", yaxis_title="Literacy %")
        st.plotly_chart(style(fig, 460, "District typologies (urbanisation × literacy, bubble = population)"),
                        width="stretch")
    with c2:
        show = prof[["districts", "pop_2023", "urban_pct", "literacy_rate", "growth_rate", "avg_hh_size"]]
        st.markdown("##### Typology profiles (averages)")
        st.dataframe(show.style.format({"pop_2023": "{:,.0f}", "urban_pct": "{:.1f}", "literacy_rate": "{:.1f}",
                                        "growth_rate": "{:.2f}", "avg_hh_size": "{:.2f}"}), width="stretch")
        pick = st.selectbox("Districts in typology", list(prof.index))
        st.write(", ".join(sorted(lab[lab["typology"] == pick]["district"])))
    insight("Typologies let planners design one policy package per group (e.g. urban-infrastructure for metros, "
            "girls' schooling + family planning for fast-growing rural districts) instead of 136 separate plans.")
